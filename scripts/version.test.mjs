import test from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { bumpVersion, checkVersion, NOTES_LIMIT, runVersion } from './version.mjs'

const hash = text => createHash('sha256').update(text).digest('hex')
const json = value => `${JSON.stringify(value, null, 2)}\n`
function fixture(t, version = '1.2.3') {
  const root = mkdtempSync(path.join(os.tmpdir(), 'oc-version-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const files = {
    'Cargo.toml': `[workspace]\nresolver = "2"\nmembers = ["app", "native"]\n\n[workspace.package]\nversion = "${version}"\n`,
    'app/Cargo.toml': '[package]\nname = "app"\nversion.workspace = true\nedition = "2021"\n',
    'app/src/lib.rs': 'pub fn app() {}\n',
    'native/Cargo.toml': '[package]\nname = "native"\nversion = "0.4.0"\nedition = "2021"\n',
    'native/src/lib.rs': 'pub fn native() {}\n',
    'Cargo.lock': `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "app"\nversion = "${version}"\n\n[[package]]\nname = "native"\nversion = "0.4.0"\n\n[[package]]\nname = "external"\nversion = "${version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "${'a'.repeat(64)}"\n`,
    'package.json': json({ name: 'app', version, scripts: { hello: 'echo hi' } }),
    'package-lock.json': json({ name: 'app', version, lockfileVersion: 3, packages: { '': { name: 'app', version }, 'node_modules/other': { version, resolved: 'https://example.org/package', integrity: 'sha512-test' } } }),
    'notes.txt': '修复真实问题。\n\n保留用户提供的发布说明。\n',
    'plugins/manifest.json': json({ version: '0.4.0' }),
  }
  files['docs/dependency-review-policy.json'] = json({ schema: 2, lockSha256: hash(files['package-lock.json']), cargoLockSha256: hash(files['Cargo.lock']), reviewedAt: '2026-11-13', advisories: [], allowedLicenses: ['MIT'], dependencyChangeReason: 'Reviewed dependencies' })
  for (const [file, text] of Object.entries(files)) { mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); writeFileSync(path.join(root, file), text) }
  return root
}
function snapshot(root) {
  const result = {}
  function walk(directory) {
    for (const item of readdirSync(directory, { withFileTypes: true })) {
      const file = path.join(directory, item.name)
      if (item.isDirectory()) walk(file); else result[path.relative(root, file)] = readFileSync(file, 'utf8')
    }
  }
  walk(root); return result
}
function change(root, file, transform) { const target = path.join(root, file); writeFileSync(target, transform(readFileSync(target, 'utf8'))) }
function repin(root) {
  change(root, 'docs/dependency-review-policy.json', text => {
    const policy = JSON.parse(text); policy.lockSha256 = hash(readFileSync(path.join(root, 'package-lock.json'))); policy.cargoLockSha256 = hash(readFileSync(path.join(root, 'Cargo.lock'))); return json(policy)
  })
}
for (const [kind, expected] of [['patch', '1.2.4'], ['minor', '1.3.0'], ['major', '2.0.0']]) {
  test(`${kind} bumps product versions, preserves dependencies and independent versions`, t => {
    const root = fixture(t), before = snapshot(root)
    const result = bumpVersion(root, kind, 'notes.txt'), after = snapshot(root)
    assert.deepEqual(result, { previousVersion: '1.2.3', version: expected, tag: `v${expected}`, files: ['Cargo.toml', 'Cargo.lock', 'package.json', 'package-lock.json', 'docs/dependency-review-policy.json', `releases/${expected}.md`] })
    assert.deepEqual(checkVersion(root), { version: expected, tag: `v${expected}` })
    assert.equal(after[`releases/${expected}.md`], before['notes.txt'])
    assert.equal(after['app/Cargo.toml'], before['app/Cargo.toml'])
    assert.equal(after['native/Cargo.toml'], before['native/Cargo.toml'])
    assert.equal(after['plugins/manifest.json'], before['plugins/manifest.json'])
    assert.equal(after['Cargo.lock'].split('[[package]]').slice(2).join('[[package]]'), before['Cargo.lock'].split('[[package]]').slice(2).join('[[package]]'))
    assert.deepEqual(JSON.parse(after['package-lock.json']).packages['node_modules/other'], JSON.parse(before['package-lock.json']).packages['node_modules/other'])
    const policy = JSON.parse(after['docs/dependency-review-policy.json']), oldPolicy = JSON.parse(before['docs/dependency-review-policy.json'])
    assert.equal(policy.lockSha256, hash(after['package-lock.json'])); assert.equal(policy.cargoLockSha256, hash(after['Cargo.lock']))
    delete policy.lockSha256; delete policy.cargoLockSha256; delete oldPolicy.lockSha256; delete oldPolicy.cargoLockSha256
    assert.deepEqual(policy, oldPolicy)
  })
}
test('check permits missing historic notes; release requires notes and matching tag', t => {
  const root = fixture(t)
  assert.deepEqual(checkVersion(root), { version: '1.2.3', tag: 'v1.2.3' })
  assert.throws(() => checkVersion(root, { release: true, env: {} }), /ENOENT/)
  mkdirSync(path.join(root, 'releases')); writeFileSync(path.join(root, 'releases/1.2.3.md'), 'Actual release notes')
  assert.deepEqual(checkVersion(root, { release: true, env: { GITHUB_REF: 'refs/tags/v1.2.3' } }), { version: '1.2.3', tag: 'v1.2.3' })
  assert.throws(() => checkVersion(root, { release: true, env: { GITHUB_REF: 'refs/tags/v9.0.0' } }), /tag must match/)
  assert.throws(() => checkVersion(root, { release: true, env: { GITHUB_REF_TYPE: 'tag', GITHUB_REF_NAME: 'v1.2.3' } }), /tag must match/)
})
for (const [name, mutate, pattern] of [
  ['npm drift', root => change(root, 'package.json', text => text.replace('1.2.3', '1.2.4')), /npm version drift/],
  ['npm lock drift', root => change(root, 'package-lock.json', text => text.replace('1.2.3', '1.2.4')), /npm version drift/],
  ['local lock drift', root => change(root, 'Cargo.lock', text => text.replace('1.2.3', '1.2.4')), /Cargo.lock version drift/],
  ['dependency hash drift', root => change(root, 'Cargo.lock', text => text.replace('a'.repeat(64), 'b'.repeat(64))), /lock hash drift/],
  ['empty notes', root => writeFileSync(path.join(root, 'notes.txt'), ' \n\t'), /nonempty/],
  ['large notes', root => writeFileSync(path.join(root, 'notes.txt'), 'a'.repeat(NOTES_LIMIT + 1)), /budget/],
  ['invalid UTF-8 notes', root => writeFileSync(path.join(root, 'notes.txt'), Buffer.from([0xff])), /encoded data/],
  ['NUL notes', root => writeFileSync(path.join(root, 'notes.txt'), 'hello\0world'), /NUL/],
  ['duplicate target', root => { mkdirSync(path.join(root, 'releases')); writeFileSync(path.join(root, 'releases/1.2.4.md'), 'Existing notes') }, /already exist/],
]) {
  test(`${name} rejects without partial modifications`, t => {
    const root = fixture(t); mutate(root); const before = snapshot(root)
    assert.throws(() => bumpVersion(root, 'patch', 'notes.txt'), pattern)
    assert.deepEqual(snapshot(root), before)
  })
}
for (const version of ['01.2.3', '1.2.3-beta.1', '1.2', '18446744073709551616.0.0']) {
  test(`rejects invalid stable version ${version}`, t => {
    const root = fixture(t, version), before = snapshot(root)
    assert.throws(() => bumpVersion(root, 'patch', 'notes.txt'), /Invalid strict stable release version/)
    assert.deepEqual(snapshot(root), before)
  })
}
test('version overflow rejects without modifying files', t => {
  const root = fixture(t, '1.2.18446744073709551615'), before = snapshot(root)
  assert.throws(() => bumpVersion(root, 'patch', 'notes.txt'), /Invalid strict stable release version/)
  assert.deepEqual(snapshot(root), before)
})
test('failed replacement restores all original bytes and removes staged output', t => {
  const root = fixture(t), before = snapshot(root); let count = 0
  assert.throws(() => bumpVersion(root, 'minor', 'notes.txt', { rename(from, to) { if (++count === 3) throw new Error('Injected disk failure'); renameSync(from, to) } }), /Injected disk failure/)
  assert.deepEqual(snapshot(root), before)
  assert.ok(!readdirSync(root).includes('releases'))
})
test('registry package matching a workspace name is not rewritten', t => {
  const root = fixture(t)
  change(root, 'Cargo.lock', text => text.replace('name = "external"', 'name = "app"')); repin(root)
  const before = readFileSync(path.join(root, 'Cargo.lock'), 'utf8').split('[[package]]').at(-1)
  bumpVersion(root, 'patch', 'notes.txt')
  assert.equal(readFileSync(path.join(root, 'Cargo.lock'), 'utf8').split('[[package]]').at(-1), before)
})
test('CLI rejects unknown or incomplete arguments before writes', t => {
  const root = fixture(t), before = snapshot(root)
  for (const args of [[], ['check', '--unknown'], ['bump', 'patch'], ['bump', 'patch', '--notes-file', 'notes.txt', 'extra']]) assert.throws(() => runVersion(args, root), /Usage/)
  assert.throws(() => runVersion(['bump', 'prerelease', '--notes-file', 'notes.txt'], root), /Bump must/)
  assert.deepEqual(snapshot(root), before)
})
test('updates version-qualified local dependency references', t => {
  const root = fixture(t)
  change(root, 'native/Cargo.toml', text => `${text}\n[dependencies]\napp = { path = "../app" }\n`)
  change(root, 'Cargo.lock', text => text.replace('version = "0.4.0"', 'version = "0.4.0"\ndependencies = [\n "app 1.2.3",\n]'))
  repin(root)
  bumpVersion(root, 'minor', 'notes.txt')
  const lock = readFileSync(path.join(root, 'Cargo.lock'), 'utf8')
  assert.match(lock, /"app 1\.3\.0"/)
  assert.doesNotMatch(lock, /"app 1\.2\.3"/)
})
test('rejects unsupported inheritance syntax explicitly without writes', t => {
  const root = fixture(t)
  change(root, 'app/Cargo.toml', text => text.replace('version.workspace = true', 'version = { workspace = true }'))
  const before = snapshot(root)
  assert.throws(() => bumpVersion(root, 'patch', 'notes.txt'), /Unsupported TOML field format/)
  assert.deepEqual(snapshot(root), before)
})
